#!/usr/bin/env node
/**
 * Generates `src-tauri/assets/game-titles.tsv` from libretro-database DAT files.
 *
 * The app only needs "serial -> title": everything else in those DATs (hashes,
 * cover art, genres) is dropped, which is why the asset stays under 2 MB.
 *
 * Usage: node scripts/build-game-titles.mjs
 */

import { writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(ROOT, "src-tauri/assets/game-titles.tsv");
const BASE = "https://raw.githubusercontent.com/libretro/libretro-database/master";

/** DAT files carrying a `serial` field, one per system the emulator catalog covers. */
const SOURCES = [
  "metadat/serial/Sony - PlayStation Portable.dat",
  "metadat/redump/Sony - PlayStation.dat",
  "metadat/redump/Sony - PlayStation 2.dat",
  "metadat/redump/Sony - PlayStation Portable.dat",
  "metadat/redump/Nintendo - GameCube.dat",
  "metadat/redump/Nintendo - Wii.dat",
  "metadat/redump/Sega - Dreamcast.dat",
];

const GAME_BLOCK = /game \(([\s\S]*?)\n\)/g;
const TITLE = /\n\tname "([^"]+)"/;
const COMMENT = /comment "([^"]+)"/;
const SERIAL = /serial "([^"]+)"/g;

/**
 * Drops the dump annotations DAT titles carry ("(USA)", "(En,Fr,De)", "(v1.01)",
 * "(Disc 1)"): the UI shows the serial next to the name when it needs to
 * disambiguate.
 */
function cleanTitle(title) {
  const cleaned = title
    .replace(/\s*\([^()]*\)/g, "")
    .replace(/\s+/g, " ")
    .trim();
  return cleaned || title.replace(/\s+/g, " ").trim();
}

function normalizeSerial(serial) {
  return serial
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, "");
}

async function fetchDat(path) {
  const response = await fetch(`${BASE}/${encodeURI(path)}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.text();
}

const titles = new Map();

for (const path of SOURCES) {
  const text = await fetchDat(path);
  let added = 0;
  for (const [, block] of text.matchAll(GAME_BLOCK)) {
    const title = block.match(TITLE)?.[1] ?? block.match(COMMENT)?.[1];
    if (!title) continue;
    for (const [, field] of block.matchAll(SERIAL)) {
      // One entry can list several serials ("SLES-12345, SLES-12346").
      for (const serial of field.split(/[,/]/)) {
        const key = normalizeSerial(serial);
        if (key.length < 5 || titles.has(key)) continue;
        titles.set(key, cleanTitle(title));
        added += 1;
      }
    }
  }
  console.log(`${path}: +${added}`);
}

const lines = [...titles.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const header = [
  "# Generated by scripts/build-game-titles.mjs — do not edit by hand.",
  "# Source: https://github.com/libretro/libretro-database (CC BY-SA 4.0).",
  `# Generated on ${new Date().toISOString().slice(0, 10)} with ${lines.length} serials.`,
];
writeFileSync(OUTPUT, `${header.join("\n")}\n${lines.map(([k, v]) => `${k}\t${v}`).join("\n")}\n`);
console.log(`\n${OUTPUT}: ${lines.length} serials`);
